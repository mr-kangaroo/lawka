function localISO(hhmm: string): ISO {
  const [h, m] = hhmm.split(':').map(Number)
  return new Date(2026, 10, h < 6 ? 9 : 8, h, m).toISOString()
}

export function createDemoShift(): Shift {
  const newId = createIdGen('demo')
  let shift: Shift = {
    id: 'demo-shift',
    date: '2026-11-08',
    startedAt: new Date(2026, 10, 8, 20, 0).toISOString(),
    authorId: 'kasia',
    notes: [],
    incidents: [],
    sections: {},
    gaps: [],
    questions: [],
    noIncidentsConfirmed: false,
  }
  for (const dn of DEMO_NOTES) {
    const createdAt = localISO(dn.hhmm)
    const note: Note = {
      id: dn.id, createdAt, text: dn.text, attachments: structuredClone(dn.attachments ?? []),
      status: 'pending', routedTo: [],
    }
    shift = { ...shift, notes: [...shift.notes, note] }
    const routed: RouteTarget[] = []
    for (const stage of dn.stages) {
      shift = applyOperations(shift, stage(shift), dn.id, createdAt, newId)
      const n = shift.notes.find((x) => x.id === dn.id)!
      for (const r of n.routedTo) {
        if (!routed.some((x) => JSON.stringify(x) === JSON.stringify(r))) routed.push(r)
      }
      n.routedTo = routed
    }
  }
  return shift
}
